import Foundation
import AppKit

/// Event-driven Clipboard manager for macOS leveraging NSPasteboard.changeCount
@MainActor
public final class ClipboardManager {
    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var lastObservedContent: String = ""
    private var watcherTask: Task<Void, Never>?
    
    public static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    public static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    public static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    public static let onePasswordType = NSPasteboard.PasteboardType("com.agilebits.onepassword")
    public static let legacyTransientType = NSPasteboard.PasteboardType("de.petermaurer.TransientPasteboardType")
    
    public var isIncognitoMode: Bool = false
    public var autoIgnoreSensitive: Bool = true
    public var onClipboardChanged: ((String) -> Void)?
    
    public init() {
        self.lastChangeCount = pasteboard.changeCount
        self.lastObservedContent = pasteboard.string(forType: .string) ?? ""
    }
    
    /// Checks if the pasteboard contains concealed, transient, or password manager items
    public func isSensitivePasteboard() -> Bool {
        guard let types = pasteboard.types else { return false }
        let sensitiveTypes: Set<NSPasteboard.PasteboardType> = [
            ClipboardManager.concealedType,
            ClipboardManager.transientType,
            ClipboardManager.autoGeneratedType,
            ClipboardManager.onePasswordType,
            ClipboardManager.legacyTransientType
        ]
        return !sensitiveTypes.isDisjoint(with: types)
    }
    
    /// Starts observing pasteboard changes
    public func startObserving() {
        stopObserving()
        lastChangeCount = pasteboard.changeCount
        
        watcherTask = Task { [weak self] in
            while !Task.isCancelled {
                try? await Task.sleep(nanoseconds: 300_000_000) // 300ms check
                guard let self = self else { break }
                
                let currentChangeCount = self.pasteboard.changeCount
                if currentChangeCount != self.lastChangeCount {
                    self.lastChangeCount = currentChangeCount
                    
                    if self.isIncognitoMode {
                        print("🕶️ Mac Clipboard change ignored: Incognito mode is active")
                        fflush(stdout)
                        continue
                    }
                    
                    if self.autoIgnoreSensitive && self.isSensitivePasteboard() {
                        print("🔒 Ignoring concealed/transient/password clipboard item")
                        fflush(stdout)
                        continue
                    }
                    
                    if let newText = self.pasteboard.string(forType: .string),
                       newText != self.lastObservedContent,
                       !newText.isEmpty {
                        self.lastObservedContent = newText
                        self.onClipboardChanged?(newText)
                    }
                }
            }
        }
    }
    
    /// Stops observing pasteboard changes
    public func stopObserving() {
        watcherTask?.cancel()
        watcherTask = nil
    }
    
    /// Sets clipboard content received from remote device without re-triggering echo.
    /// Dropped if Incognito Mode is active.
    public func setRemoteContent(_ text: String) {
        if isIncognitoMode {
            print("🕶️ Incognito active: Dropping remote clipboard update")
            fflush(stdout)
            return
        }
        guard !text.isEmpty, text != lastObservedContent else { return }
        
        lastObservedContent = text
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        lastChangeCount = pasteboard.changeCount
        print("📋 Mac Clipboard updated from remote: \(text.prefix(30))...")
    }
    
    /// Gets current clipboard text
    public func getContent() -> String {
        return pasteboard.string(forType: .string) ?? ""
    }
}